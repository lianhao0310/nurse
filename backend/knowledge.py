def detect_diseases(text: str):
    """从文本中识别涉及的疾病，返回 [(病名, 命中词)]"""
    found = []
    for disease, info in DISEASE_KB.items():
        for kw in info["keywords"]:
            if kw in text:
                found.append((disease, kw))
                break
    return found


def disease_advice(disease: str):
    """返回某病种的叮嘱与风险知识"""
    return DISEASE_KB.get(disease, {})
